// Decodes public/audio/<prefix>*.mp3 (and public/audio/music/) in headless Chromium and prints RMS, peak and crest factor
// (peak / RMS) per file, so playback trims are measured rather than guessed. Target RMS is 0.15-0.18 (0.165 here).
//   npx tsx tools/measure-audio.ts [prefix]            print only
//   npx tsx tools/measure-audio.ts --write             also (re)write src/client/audio/trims.ts for every file
// A trim is TARGET_RMS / rms, bounded to 0.1..12 and to 2.5 / peak so a spiky clip is not boosted into the limiter.
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join, sep } from 'node:path'
import { chromium } from '@playwright/test'

const TARGET_RMS = 0.165
const MAX_TRIM = 12
const root = join(import.meta.dirname, '..', 'public', 'audio')
const write = process.argv.includes('--write')
const prefix = process.argv.slice(2).find((a) => !a.startsWith('--')) ?? ''
const list = async (dir: string) => {
  try { return (await readdir(dir)).filter((f) => f.startsWith(prefix) && f.endsWith('.mp3')).sort().map((f) => join(dir, f)) } catch { return [] }
}
const files = [...(await list(root)), ...(await list(join(root, 'music')))]
const browser = await chromium.launch()
const page = await browser.newPage()
const trims: Record<string, number> = {}
const durations: Record<string, number> = {}
for (const f of files) {
  const b64 = (await readFile(f)).toString('base64')
  const r = await page.evaluate(async (data) => {
    const bytes = Uint8Array.from(atob(data), (c) => c.charCodeAt(0))
    const buf = await new OfflineAudioContext(1, 44100, 44100).decodeAudioData(bytes.buffer)
    const ch = buf.getChannelData(0)
    let sum = 0, peak = 0
    for (let i = 0; i < ch.length; i++) { const v = ch[i]!; sum += v * v; peak = Math.max(peak, Math.abs(v)) }
    const rms = Math.sqrt(sum / ch.length)
    return { rms, peak, crest: peak / rms, dur: buf.duration }
  }, b64)
  const name = f.split(sep).join('/').split('/audio/')[1]!.replace('.mp3', '').replace(/^music\//, '')
  const trim = Math.round(Math.min(MAX_TRIM, Math.max(0.1, Math.min(TARGET_RMS / Math.max(r.rms, 1e-6), 2.5 / Math.max(r.peak, 1e-6)))) * 100) / 100
  trims[name] = trim
  durations[name] = Math.round(r.dur * 100) / 100
  console.log(`${name.padEnd(36)} rms ${r.rms.toFixed(3)} peak ${r.peak.toFixed(2)} crest ${r.crest.toFixed(1)} ${r.dur.toFixed(2)}s trim ${trim}`)
}
await browser.close()
if (files.length === 0) console.log(`[measure-audio] no files match "${prefix}"`)
if (write && !prefix) {
  const obj = (o: Record<string, number>) => `{\n${Object.keys(o).sort().map((k) => `  ${JSON.stringify(k)}: ${o[k]},`).join('\n')}\n}`
  await writeFile(join(import.meta.dirname, '..', 'src', 'client', 'audio', 'trims.ts'), `// GENERATED by \`npx tsx tools/measure-audio.ts --write\`: do not edit by hand.
// TRIMS: per-asset playback multipliers (0.1..12) aiming at RMS ${TARGET_RMS} (target band 0.15-0.18). DURATIONS: decoded length in seconds (narration pauses use it).
export const TRIMS: Record<string, number> = ${obj(trims)}
export const DURATIONS: Record<string, number> = ${obj(durations)}
`)
  console.log(`[measure-audio] wrote trims.ts for ${files.length} files`)
}
